"""Arabic translation of *Chrono Trigger* (USA): the dialogue, table by table.

The game keeps its dialogue in string tables (``engines.chrono_trigger``), one
for a run of its locations: a table's strings are named by their number in
it. The translation takes whole tables (``TABLES``): the first, at $F7:0000,
holds Crono's house and Truce in the year 1000 and in 600, Truce Canyon with
the Gate, the prison's cell, Lab 32 with Johnny's race, the Proto Dome with
Robo's awakening, the Sun Keep and the Geno Dome; the second, at $FC:BA00,
holds Leene Square with the Millennial Fair and Lucca's Telepod, the trial,
the castle's cellars with the Rainbow Shell, Melchior's hut, Norstein
Bekkler's tent, the Tyrano Lair's cells, the Lavos crater, Zeal's sealed
palace and Death Peak; the third, at $F7:4900, holds Castle Guardia in 600
and 1000, the domes of 2300 A.D., Medina, the End of Time with Gaspar and
Spekkio, Ozzie's and Magus's scenes, the Blackbird and the Reptites' land.
Each entry's id is its table's key and its number.

Each original is pinned by its table, its number there and the SHA-256 of
its bytes (its zero included), so the translation can be checked without the
ROM and the build refuses another text. Its command skeleton
(``engines.chrono_trigger.command_skeleton``: its codes with their bytes, but
the layout) may be pinned too, so the translation's commands are checked
without the ROM as the build checks them against the ROM's; the build's
report carries every original's, for pinning.

The Arabic lives in ``classic_retro/translations/chrono-trigger.json``: logical
Unicode Arabic in the engine's notation (``engines.chrono_trigger_arabic``): a
line for each box, ``{line}`` where a line of the box must end, ``{choice}``
at a choice's line (on the lines the event makes choices, ``DECISIONS``),
``{box auto}`` for a box that does not wait, the
English's pauses and codes as tokens, and a ``{name}`` token for a name the
game writes.
"""


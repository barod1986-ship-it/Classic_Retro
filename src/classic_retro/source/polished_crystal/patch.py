"""The engine patch: the overlay's changes to the game's code, stored without its text.

The right-to-left engine (``home/rtl.asm``, ``engine/gfx/rtl_*.asm`` and the
changes to ``home/text.asm``), the naming screen, the menus and the screens the
overlay turns around are a patch on the pinned source. Each hunk is stored as:

- the 1-based line where it starts in the pristine file;
- how many lines it removes, and the SHA-256 of those lines (joined by line
  ends), never the lines: they are the game's source, often its text;
- the lines it adds: the overlay's own code and comments.

An added line that must repeat a string of the game (the battle text's "foe"
word moves from before the name to after it) holds a reference to that string
instead: ``[k, j]`` is the content of the ``j``-th string literal of the hunk's
``k``-th removed line. ``make_engine_patch`` refuses an added string with Latin
letters it cannot express that way, so the patch holds no English of the game.

Files the overlay generates (fonts, the Pokédex's tilemaps, the charmap, the
n-grams, the keyboards and the shaping tables) are left out of the patch:
``prepare`` writes them from the pinned originals and the translation.
"""

from __future__ import annotations

import hashlib
import json
import re
import subprocess
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from functools import cache
from importlib.resources import files
from pathlib import Path
from typing import Any

from classic_retro.core.errors import ClassicRetroError, ErrorCode

FORMAT = "polished-crystal-engine-patch/1"

# Generated by prepare, so never part of the engine patch.
GENERATED = (
    "constants/charmap.asm",
    "data/text/ngrams.asm",
    "data/text/input_chars.asm",
    "data/text/arabic_shaping.asm",
    "data/text/lucky_key_phrase.asm",
    "gfx/font/*.png",
    "gfx/pokedex/*.tilemap",
)
# Directives whose string is not text of the game: file names, section names, messages.
_CODE_STRINGS = re.compile(
    r"^\s*(?:[\w.]+:+\s*)?(INCLUDE|INCBIN|SECTION|LOAD|assert|static_assert|fail|warn|println|print"
    r"|PUSHS|POPS|OPT|DEF\s+\w+\s+EQUS)\b",
    re.IGNORECASE,
)
_LATIN = re.compile(r"[A-Za-z]")

Line = str | list[object]


@dataclass(frozen=True, slots=True)
class Hunk:
    start: int
    removed: int
    removed_sha256: str
    added: tuple[Line, ...]


@dataclass(frozen=True, slots=True)
class FilePatch:
    path: str
    hunks: tuple[Hunk, ...] = ()
    new_lines: tuple[str, ...] | None = None

    @property
    def is_new(self) -> bool:
        return self.new_lines is not None


@dataclass(frozen=True, slots=True)
class EnginePatch:
    base: str
    engine: str
    files: tuple[FilePatch, ...]
    digest: str

    def paths(self) -> list[str]:
        return [patch.path for patch in self.files]

    def modified(self) -> list[str]:
        """The pristine files the patch changes (new files are not in the source)."""
        return [patch.path for patch in self.files if not patch.is_new]


def lines_sha256(lines: Sequence[str]) -> str:
    return hashlib.sha256("\n".join(lines).encode("utf-8")).hexdigest()


def string_literals(code: str) -> list[str]:
    """The contents of the ``"..."`` literals of a source line's code, escapes kept."""
    return [match.group(1) for match in re.finditer(r'"((?:[^"\\]|\\.)*)"', _code(code))]


def _code(line: str) -> str:
    """A line without its comment (a ``;`` outside strings)."""
    in_string = False
    index = 0
    while index < len(line):
        char = line[index]
        if in_string and char == "\\":
            index += 2
            continue
        if char == '"':
            in_string = not in_string
        elif char == ";" and not in_string:
            return line[:index]
        index += 1
    return line


def _text_letters(literal: str) -> bool:
    """Whether a literal holds Latin letters outside ``<CODES>`` and ``{interpolations}``."""
    return bool(_LATIN.search(re.sub(r"<[^<>]*>|\{[^{}]*\}", "", literal)))


def resolve_line(line: Line, removed: Sequence[str]) -> str:
    """An added line, its references to the removed lines' strings filled in."""
    if isinstance(line, str):
        return line
    out = []
    for part in line:
        if isinstance(part, str):
            out.append(part)
        else:
            row, number = part
            out.append(string_literals(removed[row])[number])
    return "".join(out)


def apply_file(patch: FilePatch, text: str | None) -> str:
    """The patched text of one file; ``text`` is the pristine text (None for a new file)."""
    if patch.is_new:
        if text is not None:
            raise ClassicRetroError(
                ErrorCode.SOURCE_BASELINE_MISMATCH, f"{patch.path} exists; the patch adds it"
            )
        return "\n".join(patch.new_lines or ()) + "\n"
    if text is None:
        raise ClassicRetroError(ErrorCode.SOURCE_BASELINE_MISMATCH, f"{patch.path} is missing")
    lines = text.split("\n")
    for hunk in sorted(patch.hunks, key=lambda hunk: hunk.start, reverse=True):
        removed = lines[hunk.start - 1 : hunk.start - 1 + hunk.removed]
        if len(removed) != hunk.removed or lines_sha256(removed) != hunk.removed_sha256:
            raise ClassicRetroError(
                ErrorCode.SOURCE_BASELINE_MISMATCH,
                f"{patch.path}: the lines the engine patch replaces at {hunk.start} differ",
            )
        lines[hunk.start - 1 : hunk.start - 1 + hunk.removed] = [
            resolve_line(line, removed) for line in hunk.added
        ]
    return "\n".join(lines)


def apply(patch: EnginePatch, texts: Mapping[str, str | None]) -> dict[str, str]:
    """Every file the patch touches, patched; ``texts`` holds their pristine texts."""
    return {item.path: apply_file(item, texts.get(item.path)) for item in patch.files}


def _line_to_json(line: Line) -> object:
    return line


def to_dict(patch: EnginePatch) -> dict[str, Any]:
    files_ = []
    for item in patch.files:
        if item.is_new:
            files_.append({"path": item.path, "new": list(item.new_lines or ())})
        else:
            files_.append(
                {
                    "path": item.path,
                    "hunks": [
                        [hunk.start, hunk.removed, hunk.removed_sha256, list(hunk.added)]
                        for hunk in item.hunks
                    ],
                }
            )
    return {"format": FORMAT, "base": patch.base, "engine": patch.engine, "files": files_}


def dumps(patch: EnginePatch) -> str:
    """The patch as shipped: one hunk header and one added line a line."""
    data = to_dict(patch)
    lines = [
        "{",
        f'  "format": {json.dumps(data["format"])},',
        f'  "base": {json.dumps(data["base"])},',
        f'  "engine": {json.dumps(data["engine"])},',
        '  "files": [',
    ]
    for number, item in enumerate(data["files"]):
        tail = "," if number + 1 < len(data["files"]) else ""
        lines.append(f'    {{"path": {json.dumps(item["path"])},')
        if "new" in item:
            lines.append('     "new": [')
            body = [f"       {json.dumps(line, ensure_ascii=False)}" for line in item["new"]]
            lines += [line + ("," if k + 1 < len(body) else "") for k, line in enumerate(body)]
            lines.append("     ]}" + tail)
            continue
        lines.append('     "hunks": [')
        for k, (start, removed, sha, added) in enumerate(item["hunks"]):
            lines.append(f"       [{start}, {removed}, {json.dumps(sha)}, [")
            body = [f"         {json.dumps(line, ensure_ascii=False)}" for line in added]
            lines += [line + ("," if i + 1 < len(body) else "") for i, line in enumerate(body)]
            lines.append("       ]]" + ("," if k + 1 < len(item["hunks"]) else ""))
        lines.append("     ]}" + tail)
    lines += ["  ]", "}"]
    return "\n".join(lines) + "\n"


def from_dict(data: Mapping[str, Any], digest: str = "") -> EnginePatch:
    if data.get("format") != FORMAT:
        raise ClassicRetroError(
            ErrorCode.INVALID_REFERENCE, f"Not a {FORMAT} file: {data.get('format')}"
        )
    items = []
    for item in data["files"]:
        if "new" in item:
            items.append(FilePatch(item["path"], new_lines=tuple(item["new"])))
        else:
            hunks = tuple(
                Hunk(start, removed, sha, tuple(added))
                for start, removed, sha, added in item["hunks"]
            )
            items.append(FilePatch(item["path"], hunks))
    return EnginePatch(data["base"], data["engine"], tuple(items), digest)


@cache
def builtin_engine_patch() -> EnginePatch:
    """The engine patch the overlay ships (``data/engine_patch.json``)."""
    resource = files("classic_retro.source.polished_crystal").joinpath("data", "engine_patch.json")
    return load_engine_patch(resource.read_bytes())


def load_engine_patch(raw: bytes) -> EnginePatch:
    """An engine patch file; its digest is the same in a checkout with CRLF line endings."""
    raw = raw.replace(b"\r\n", b"\n")
    return from_dict(json.loads(raw.decode("utf-8")), hashlib.sha256(raw).hexdigest())


# --- making the patch (for the overlay's developers) ------------------------------------

_HUNK = re.compile(r"^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@")


def _git(repository: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", "-C", str(repository), *args], capture_output=True, text=True, check=False
    )
    if result.returncode:
        raise ClassicRetroError(
            ErrorCode.SOURCE_PATCH_FAILED, f"git {' '.join(args)}: {result.stderr.strip()}"
        )
    return result.stdout


def _template(line: str, removed: Sequence[str]) -> Line:
    """An added line, any Latin string of the game in it replaced by a reference."""
    if _CODE_STRINGS.match(line) or not any(_text_letters(s) for s in string_literals(line)):
        return line
    candidates = [
        (row, number, literal)
        for row, removed_line in enumerate(removed)
        for number, literal in enumerate(string_literals(removed_line))
        if _text_letters(literal)
    ]
    parts: list[object] = []
    rest = line
    code_end = len(_code(line))
    position = 0
    for match in re.finditer(r'"((?:[^"\\]|\\.)*)"', line[:code_end]):
        content = match.group(1)
        if not _text_letters(content):
            continue
        for row, number, literal in sorted(candidates, key=lambda item: -len(item[2])):
            at = content.find(literal)
            if at >= 0 and not _text_letters(content[:at] + content[at + len(literal) :]):
                start = match.start(1) + at
                parts += [line[position:start], [row, number]]
                position = start + len(literal)
                break
        else:
            raise ClassicRetroError(
                ErrorCode.SOURCE_PATCH_FAILED,
                f"an added line holds Latin text that is no string of the lines it replaces: {line!r}",
            )
    rest = line[position:]
    if rest:
        parts.append(rest)
    return parts


def _is_generated(path: str, generated: Iterable[str]) -> bool:
    return any(Path(path).match(pattern) for pattern in generated)


def parse_diff(diff: str, base_texts: Mapping[str, str]) -> list[FilePatch]:
    """File patches from ``git diff -U0`` output; ``base_texts`` are the pristine files."""
    patches: list[FilePatch] = []
    current: dict[str, Any] | None = None

    def close() -> None:
        if current is None:
            return
        if current["new"]:
            patches.append(FilePatch(current["path"], new_lines=tuple(current["added_all"])))
        else:
            patches.append(FilePatch(current["path"], tuple(current["hunks"])))

    hunk: dict[str, Any] | None = None

    def close_hunk() -> None:
        nonlocal hunk
        if hunk is None or current is None or current["new"]:
            hunk = None
            return
        base = base_texts[current["path"]].split("\n")
        removed = base[hunk["start"] - 1 : hunk["start"] - 1 + hunk["count"]]
        if removed != hunk["removed"]:
            raise ClassicRetroError(
                ErrorCode.SOURCE_PATCH_FAILED, f"{current['path']}: the diff does not fit its base"
            )
        added = tuple(_template(line, removed) for line in hunk["added"])
        current["hunks"].append(Hunk(hunk["start"], hunk["count"], lines_sha256(removed), added))
        hunk = None

    for raw in diff.split("\n"):
        if raw.startswith("diff --git "):
            close_hunk()
            close()
            path = raw.split(" b/", 1)[1]
            current = {"path": path, "new": False, "hunks": [], "added_all": []}
            continue
        if current is None:
            continue
        if raw.startswith("new file mode"):
            current["new"] = True
        elif raw.startswith(("deleted file mode", "Binary files", "rename ", "similarity")):
            raise ClassicRetroError(
                ErrorCode.SOURCE_PATCH_FAILED, f"{current['path']}: unsupported change: {raw}"
            )
        elif raw.startswith("\\ No newline"):
            raise ClassicRetroError(
                ErrorCode.SOURCE_PATCH_FAILED, f"{current['path']}: a file must end with a line end"
            )
        elif raw.startswith("@@"):
            close_hunk()
            match = _HUNK.match(raw)
            if match is None:
                raise ClassicRetroError(ErrorCode.SOURCE_PATCH_FAILED, f"bad hunk header {raw}")
            old_start, old_count = int(match.group(1)), int(match.group(2) or "1")
            # A hunk that only adds lines names the line after which they go.
            start = old_start if old_count else old_start + 1
            hunk = {"start": start, "count": old_count, "removed": [], "added": []}
        elif hunk is not None and raw.startswith("-") and not raw.startswith("---"):
            hunk["removed"].append(raw[1:])
        elif hunk is not None and raw.startswith("+") and not raw.startswith("+++"):
            hunk["added"].append(raw[1:])
            if current["new"]:
                current["added_all"].append(raw[1:])
    close_hunk()
    close()
    for item in patches:
        for line in item.new_lines or ():
            if any(_text_letters(s) for s in string_literals(line)) and not _CODE_STRINGS.match(
                line
            ):
                raise ClassicRetroError(
                    ErrorCode.SOURCE_PATCH_FAILED,
                    f"{item.path}: a new file holds a Latin string: {line!r}",
                )
    return patches


def make_engine_patch(
    repository: Path, base: str, ref: str, generated: Iterable[str] = GENERATED
) -> EnginePatch:
    """The patch from ``base`` to ``ref`` of an engine repository, without the generated files."""
    generated = tuple(generated)
    engine = _git(repository, "rev-parse", ref).strip()
    base_commit = _git(repository, "rev-parse", base).strip()
    names = [
        name
        for name in _git(repository, "diff", "--name-only", "--no-renames", base_commit, engine)
        .strip()
        .split("\n")
        if name and not _is_generated(name, generated)
    ]
    diff = _git(
        repository, "diff", "-U0", "--no-color", "--no-renames", base_commit, engine, "--", *names
    )
    base_texts = {}
    for name in names:
        try:
            base_texts[name] = _git(repository, "show", f"{base_commit}:{name}")
        except ClassicRetroError:
            continue
    patches = parse_diff(diff, base_texts)
    patch = EnginePatch(base_commit, engine, tuple(patches), "")
    # The patch rebuilds the engine branch's files exactly.
    for item in patch.files:
        rebuilt = apply_file(item, base_texts.get(item.path))
        if rebuilt != _git(repository, "show", f"{engine}:{item.path}"):
            raise ClassicRetroError(
                ErrorCode.SOURCE_PATCH_FAILED, f"{item.path}: the patch does not rebuild it"
            )
    return patch

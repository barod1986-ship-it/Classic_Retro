TARGET = "chrono-trigger"


def chrono_trigger_arabic_messages(
    translations: TranslationSet | None = None,
) -> tuple[ChronoTriggerMessage, ...]:
    """Every translated message, in the order of the tables and their numbers."""
    texts = (translations or builtin_translation_set(TARGET)).texts(tuple(_SOURCES))
    messages = []
    for key, (index, digest, skeleton) in _SOURCES.items():
        table = TABLES[key.rsplit(".", 1)[0]]
        messages.append(
            ChronoTriggerMessage(
                key, table.address, index, digest, texts[key], skeleton, DECISIONS.get(key)
            )
        )
    return tuple(messages)
